"""Video generation tools for FitPulse Coach using gemini-omni-flash-preview."""

from __future__ import annotations

import base64
import uuid
from typing import Any
from google import genai
from google.genai import types
from google.cloud import storage
from google.adk.tools import ToolContext

# Hardcoded project ID and public bucket name to prevent runtime project number resolution issues
GCP_PROJECT_ID = "qwiklabs-gcp-04-ec0b87ee001f"
MEDIA_BUCKET_NAME = "fitpulse-coach-media-qwiklabs-gcp-04-ec0b87ee001f"


def generate_exercise_video(prompt: str, tool_context: ToolContext | None = None) -> dict[str, Any]:
    """Generate a short video demonstrating an exercise or fitness movement in FitPulse Coach's domain.

    Uses Google's Omni model (gemini-omni-flash-preview) in the global region.
    The generated video is:
      1. Saved with tool_context.save_artifact so it appears in the Playground's Artifacts panel.
      2. Uploaded directly to the public Cloud Storage bucket in-memory (no local file written).
      3. Returned with its public HTTPS URL (https://storage.googleapis.com/<bucket>/<object>).

    Args:
        prompt: Visual description of the exercise movement, technique demo, or fitness achievement video to generate.
        tool_context: ADK ToolContext injected automatically by the runtime.

    Returns:
        A dictionary containing the status, prompt, filename, and public https URL of the uploaded video.
    """
    try:
        client = genai.Client(vertexai=True, project=GCP_PROJECT_ID, location="global")

        interaction = client.interactions.create(
            model="gemini-omni-flash-preview",
            input=[{"type": "text", "text": prompt}],
            response_format=[{"type": "video", "delivery": "inline", "duration": "4s"}],
            store=False,
        )

        video_bytes: bytes | None = None
        mime_type = "video/mp4"

        if hasattr(interaction, "output_video") and interaction.output_video:
            out = interaction.output_video
            if hasattr(out, "mime_type") and out.mime_type:
                mime_type = out.mime_type
            if hasattr(out, "data") and out.data:
                raw_data = out.data
                if isinstance(raw_data, str):
                    video_bytes = base64.b64decode(raw_data)
                elif isinstance(raw_data, bytes):
                    video_bytes = raw_data

        # Fallback inspection of interaction.steps
        if not video_bytes and hasattr(interaction, "steps") and interaction.steps:
            for step in interaction.steps:
                if hasattr(step, "content") and step.content:
                    for c in step.content:
                        if getattr(c, "type", None) == "video" and getattr(c, "data", None):
                            raw_data = c.data
                            if getattr(c, "mime_type", None):
                                mime_type = c.mime_type
                            if isinstance(raw_data, str):
                                video_bytes = base64.b64decode(raw_data)
                            elif isinstance(raw_data, bytes):
                                video_bytes = raw_data
                            break
                if video_bytes:
                    break

        if not video_bytes:
            return {"error": "No video data was generated by gemini-omni-flash-preview for the given prompt."}

        filename = f"exercise_{uuid.uuid4().hex[:8]}.mp4"

        # 1. Save artifact in ToolContext for the Playground's Artifacts panel
        if tool_context is not None:
            try:
                artifact_part = types.Part.from_bytes(data=video_bytes, mime_type=mime_type)
                tool_context.save_artifact(filename=filename, artifact=artifact_part)
            except Exception as e:
                print(f"Warning: tool_context.save_artifact failed: {e}")

        # 2. Upload video bytes directly to public Cloud Storage (in-memory, no local file written)
        storage_client = storage.Client(project=GCP_PROJECT_ID)
        bucket = storage_client.bucket(MEDIA_BUCKET_NAME)
        blob = bucket.blob(filename)
        blob.upload_from_string(video_bytes, content_type=mime_type)

        public_url = f"https://storage.googleapis.com/{MEDIA_BUCKET_NAME}/{filename}"

        return {
            "status": "success",
            "prompt": prompt,
            "filename": filename,
            "public_url": public_url,
            "mime_type": mime_type,
        }
    except Exception as e:
        return {"error": f"Video generation failed: {e}"}
