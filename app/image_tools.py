"""Image generation tools for FitPulse Coach using gemini-3.1-flash-lite-image."""

from __future__ import annotations

import uuid
from typing import Any
from google import genai
from google.genai import types
from google.cloud import storage
from google.adk.tools import ToolContext

# Hardcoded project ID and bucket name to prevent runtime project number resolution issues on Agent Platform
GCP_PROJECT_ID = "qwiklabs-gcp-04-ec0b87ee001f"
MEDIA_BUCKET_NAME = "fitpulse-coach-media-qwiklabs-gcp-04-ec0b87ee001f"


def generate_fitness_image(prompt: str, tool_context: ToolContext | None = None) -> dict[str, Any]:
    """Generate a fitness image (achievement badge, workout milestone visual, or meal plating idea).

    Uses the gemini-3.1-flash-lite-image model in the global region.
    The generated image is saved as a session artifact for the Playground's Artifacts panel,
    uploaded directly to public Cloud Storage, and its public HTTPS URL is returned.

    Args:
        prompt: Detailed visual prompt describing the fitness badge, meal, or workout milestone to generate.
        tool_context: ADK ToolContext injected automatically by the runtime.

    Returns:
        A dictionary containing the status, prompt, filename, and public https URL of the uploaded image.
    """
    try:
        client = genai.Client(vertexai=True, project=GCP_PROJECT_ID, location="global")
        response = client.models.generate_content(
            model="gemini-3.1-flash-lite-image",
            contents=prompt,
            config=types.GenerateContentConfig(
                response_modalities=["IMAGE"],
            ),
        )

        image_bytes: bytes | None = None
        mime_type = "image/png"

        if response.candidates:
            for candidate in response.candidates:
                if candidate.content and candidate.content.parts:
                    for part in candidate.content.parts:
                        if part.inline_data and part.inline_data.data:
                            image_bytes = part.inline_data.data
                            if part.inline_data.mime_type:
                                mime_type = part.inline_data.mime_type
                            break
                if image_bytes:
                    break

        if not image_bytes:
            return {"error": "No image data was generated by the model for the given prompt."}

        ext = "jpg" if "jpeg" in mime_type else "png"
        filename = f"badge_{uuid.uuid4().hex[:8]}.{ext}"

        # 1. Save artifact in ToolContext for the Playground's Artifacts panel
        if tool_context is not None:
            try:
                artifact_part = types.Part.from_bytes(data=image_bytes, mime_type=mime_type)
                tool_context.save_artifact(filename=filename, artifact=artifact_part)
            except Exception as e:
                # Log non-fatal artifact save warning
                print(f"Warning: tool_context.save_artifact failed: {e}")

        # 2. Upload image bytes directly to Cloud Storage (in-memory, no local file written)
        storage_client = storage.Client(project=GCP_PROJECT_ID)
        bucket = storage_client.bucket(MEDIA_BUCKET_NAME)
        blob = bucket.blob(filename)
        blob.upload_from_string(image_bytes, content_type=mime_type)

        public_url = f"https://storage.googleapis.com/{MEDIA_BUCKET_NAME}/{filename}"

        return {
            "status": "success",
            "prompt": prompt,
            "filename": filename,
            "public_url": public_url,
            "mime_type": mime_type,
        }
    except Exception as e:
        return {"error": f"Image generation failed: {e}"}
